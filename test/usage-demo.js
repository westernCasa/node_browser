// Unit checks for core/usage.js (B64).
const { Usage, COUNTS, localDay } = require("../core/usage");
let failed = 0;
const check = (name, ok) => { if (!ok) failed++; console.log(ok ? "✓" : "✗", name); };
let file = null;
const io = { read: () => file, write: (t) => { file = t; } };
let day = new Date(2026, 9, 21, 10);
const u = new Usage(io, () => day);
check("starts empty", u.daysUsed() === 0 && Object.keys(COUNTS).every((k) => u.data.counts[k] === 0));
u.count("pins");
check("a count marks the day", u.daysUsed() === 1 && u.data.days[0] === "2026-10-21");
check("unknown names are ignored", u.count("pages", 5) === false && u.count("__proto__") === false && !("pages" in u.data.counts));
u.count("suggestionsShown", 5000);
check("one call adds at most 1000", u.data.counts.suggestionsShown === 1000);
check("negative and junk add nothing", u.count("hides", -3) === false && u.count("hides", "x") === false && u.data.counts.hides === 0);
u.touch(); u.touch();
check("same day counted once", u.daysUsed() === 1);
day = new Date(2026, 9, 23, 9); u.touch();
day = new Date(2026, 9, 22, 9); u.touch();
check("days kept in order", u.data.days.join(",") === "2026-10-21,2026-10-22,2026-10-23");
u.count("suggestionsOpened", 25);
u.saveNow();
const again = new Usage(io, () => day);
check("saved and loaded", again.daysUsed() === 3 && again.data.counts.pins === 1 && again.data.counts.suggestionsOpened === 25);
const s = again.summary({ version: "0.9.1", os: "Windows 11" });
check("summary has version, system, days and rate", /Version 0\.9\.1 · Windows 11/.test(s) && /Days used: 3 \(first 2026-10-21, last 2026-10-23\)/.test(s) && /opened: 25 \(2\.5%\)/.test(s));
file = '{"days":["2026-10-01","<script>","x"],"counts":{"pins":"7","hides":-4,"evil":9}}';
const bad = new Usage(io);
check("bad saved data is cleaned", bad.daysUsed() === 1 && bad.data.counts.pins === 7 && bad.data.counts.hides === 0 && !("evil" in bad.data.counts));
file = "not json";
check("unreadable file starts fresh", new Usage(io).daysUsed() === 0);
check("localDay pads", localDay(new Date(2026, 0, 5)) === "2026-01-05");
console.log(failed ? `${failed} failed` : "all usage checks passed");
process.exit(failed ? 1 : 0);
