// Builds NODE's built-in extension for the Chromium build (B51) into
// browser/extension/dist, and writes the manifest as a C++ string for the
// component loader patch (browser/patches/0002-node-builtin-extension.patch):
//
//   node browser/extension/build.js            build dist/ and manifest.inc
//   node browser/extension/build.js --src DIR  also copy manifest.inc into a
//                                              Chromium source tree
//
// In the NODE Chromium build the extension is a component extension: it is
// part of the browser, cannot be turned off or removed, and is not listed in
// chrome://extensions. Its files are copied into the app bundle at
// "NODE Chromium Framework.framework/Resources/node_extension" by
// browser/build.sh.
//
// The shared core/ modules are bundled with esbuild. The page scripts in
// core/page-scripts.js are code strings (the Electron app runs them with
// executeJavaScript); extensions cannot evaluate strings, so this build writes
// them into content.js as plain code.
const fs = require("fs");
const path = require("path");
const esbuild = require("esbuild");
const scripts = require("../../core/page-scripts");
const pkg = require("../../package.json");

const ROOT = path.join(__dirname, "..", "..");
const SRC = path.join(__dirname, "src");
const OUT = path.join(__dirname, "dist");
const KEY = fs.readFileSync(path.join(__dirname, "key.pub.b64"), "utf8").trim();
// The ID Chromium derives from KEY. Checked below so the two cannot drift.
const EXTENSION_ID = "bdcmchdlmdgddldgdgapcmipndcgpgod";

function idFromKey(b64) {
  const hex = require("crypto").createHash("sha256").update(Buffer.from(b64, "base64")).digest("hex").slice(0, 32);
  return [...hex].map((c) => String.fromCharCode(97 + parseInt(c, 16))).join("");
}
if (idFromKey(KEY) !== EXTENSION_ID) throw new Error(`key.pub.b64 gives ID ${idFromKey(KEY)}, expected ${EXTENSION_ID}`);

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, "fonts"), { recursive: true });

const manifest = {
  manifest_version: 3,
  name: "NODE",
  // Chromium versions are 1-4 dot-separated numbers: drop "-beta" and the like.
  version: pkg.version.replace(/[^0-9.].*$/, ""),
  description: "NODE's research panel: suggestions from the page you are reading, autoplay in up to 4 tabs, center on click, Talk.",
  key: KEY,
  icons: { 128: "icon.png" },
  // Toolbar button: the kit's `suggest` icon; it opens the NODE side panel.
  action: {
    default_title: "Suggestions panel",
    default_icon: { 16: "ui/icons/png/suggest-on-light-16.png", 32: "ui/icons/png/suggest-on-light-32.png" },
  },
  commands: { _execute_action: { suggested_key: { default: "Alt+Shift+N" }, description: "Open the NODE panel" } },
  side_panel: { default_path: "sidepanel.html" },
  background: { service_worker: "background.js", type: "module" },
  permissions: ["sidePanel", "tabs", "storage"],
  host_permissions: ["<all_urls>"],
  content_scripts: [{ matches: ["http://*/*", "https://*/*"], js: ["content.js"], run_at: "document_idle", all_frames: false }],
};
const manifestJson = JSON.stringify(manifest, null, 2);
fs.writeFileSync(path.join(OUT, "manifest.json"), manifestJson);

const content = `// Generated by browser/extension/build.js from core/page-scripts.js. Do not edit.
// Content scripts run in an isolated world, so the page cannot see these.
(() => {
  const extract = () => ${scripts.extractionScript()};
  const autoplay = () => ${scripts.autoplayScript("on")};
  const pauseForLimit = () => ${scripts.pauseForLimitScript()};
  const resume = () => ${scripts.resumeScript()};
  const anyPlaying = () => ${scripts.anyPlayingScript()};
  ${scripts.centerOnClickScript()};
  const send = (m) => chrome.runtime.sendMessage(m).catch(() => {});
  // Media in this tab started or stopped: tell the playback limit.
  document.addEventListener("play", () => send({ type: "media-playing" }), true);
  const stopped = () => setTimeout(() => { if (!anyPlaying()) send({ type: "media-stopped" }); }, 50);
  document.addEventListener("pause", stopped, true);
  document.addEventListener("ended", stopped, true);
  chrome.runtime.onMessage.addListener((msg, _sender, reply) => {
    if (msg.type === "extract") reply(extract());
    else if (msg.type === "pause-for-limit") reply(pauseForLimit());
    else if (msg.type === "resume") reply(resume());
    return false;
  });
  autoplay();
  window.addEventListener("load", autoplay);
  send({ type: "page-settled" });
})();
`;
fs.writeFileSync(path.join(OUT, "content.js"), content);

for (const entry of ["background.js", "sidepanel.js"]) {
  esbuild.buildSync({
    entryPoints: [path.join(SRC, entry)],
    bundle: true,
    format: entry === "background.js" ? "esm" : "iife",
    platform: "browser",
    target: "chrome120",
    outfile: path.join(OUT, entry),
    logLevel: "warning",
  });
}

for (const f of ["sidepanel.html", "panel.css", "menu.html", "menu.js", "toolbar-icon.js"]) fs.copyFileSync(path.join(SRC, f), path.join(OUT, f));
// NODE UI kit: node-ui.css, node-ui.js, icons/ (SVG, sprite, toolbar PNGs), fonts/.
fs.cpSync(path.join(SRC, "ui"), path.join(OUT, "ui"), { recursive: true });
fs.copyFileSync(path.join(ROOT, "renderer", "styles.css"), path.join(OUT, "styles.css"));
for (const f of fs.readdirSync(path.join(ROOT, "renderer", "fonts"))) fs.copyFileSync(path.join(ROOT, "renderer", "fonts", f), path.join(OUT, "fonts", f));
fs.copyFileSync(path.join(ROOT, "build", "icon.png"), path.join(OUT, "icon.png"));

// The component loader patch includes this file: the manifest as a C++ raw
// string. Component extensions are registered from an in-memory manifest; the
// files are then read from the extension's folder in the app bundle.
const inc = `// Generated by browser/extension/build.js. Do not edit.\n// NODE built-in extension, ID ${EXTENSION_ID}.\nR"NODEMANIFEST(${manifestJson})NODEMANIFEST"\n`;
fs.writeFileSync(path.join(__dirname, "manifest.inc"), inc);

const srcFlag = process.argv.indexOf("--src");
if (srcFlag > 0) {
  const dest = path.join(process.argv[srcFlag + 1], "chrome", "browser", "extensions", "node_extension_manifest.inc");
  fs.copyFileSync(path.join(__dirname, "manifest.inc"), dest);
  console.log("Wrote", dest);
}
console.log(`NODE extension ${manifest.version} (${EXTENSION_ID}) built in ${path.relative(process.cwd(), OUT)}: ${fs.readdirSync(OUT).join(", ")}`);
