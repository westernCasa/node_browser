const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("scout", {
  createTab: (url) => ipcRenderer.invoke("tab:create", url),
  closeTab: (id) => ipcRenderer.invoke("tab:close", id),
  activateTab: (id) => ipcRenderer.invoke("tab:activate", id),
  navigate: (id, url) => ipcRenderer.invoke("tab:navigate", id, url),
  goBack: (id) => ipcRenderer.invoke("tab:back", id),
  goForward: (id) => ipcRenderer.invoke("tab:forward", id),
  reload: (id) => ipcRenderer.invoke("tab:reload", id),
  setLayout: (mode) => ipcRenderer.invoke("layout:set", mode),
  setSidebarWidth: (w) => ipcRenderer.invoke("layout:sidebar", w),
  setLibraryOpen: (open) => ipcRenderer.invoke("layout:library", open),
  extract: (id) => ipcRenderer.invoke("page:extract", id),
  suggest: (keywords, excludeUrl) => ipcRenderer.invoke("suggest:search", keywords, excludeUrl),
  preview: (url, keywords) => ipcRenderer.invoke("suggest:preview", url, keywords),
  keywords: (id, banned, opts) => ipcRenderer.invoke("page:keywords", id, banned, opts),
  suggestFor: (payload) => ipcRenderer.invoke("suggest:for", payload),
  getSettings: () => ipcRenderer.invoke("settings:get"),
  testAI: (draft) => ipcRenderer.invoke("ai:test", draft),
  editRules: () => ipcRenderer.invoke("rules:edit"),
  findStart: (id, text, opts) => ipcRenderer.invoke("find:start", id, text, opts),
  researchGet: () => ipcRenderer.invoke("research:get"),
  researchList: () => ipcRenderer.invoke("research:list"),
  researchNew: (name) => ipcRenderer.invoke("research:new", name),
  researchSwitch: (id) => ipcRenderer.invoke("research:switch", id),
  researchRename: (name) => ipcRenderer.invoke("research:rename", name),
  researchPins: (pins) => ipcRenderer.invoke("research:pins", pins),
  researchVisit: (url, title, keywords) => ipcRenderer.invoke("research:visit", url, title, keywords),
  researchOpened: (item) => ipcRenderer.invoke("research:opened", item),
  researchDismiss: (url) => ipcRenderer.invoke("research:dismiss", url),
  researchUndismiss: () => ipcRenderer.invoke("research:undismiss"),
  researchExport: () => ipcRenderer.invoke("research:export"),
  findStop: (id) => ipcRenderer.invoke("find:stop", id),
  zoom: (id, step) => ipcRenderer.invoke("tab:zoom", id, step),
  historySearch: (q, limit) => ipcRenderer.invoke("history:search", q, limit),
  historyClear: () => ipcRenderer.invoke("history:clear"),
  historyRemove: (url) => ipcRenderer.invoke("history:remove", url),
  reloadRules: () => ipcRenderer.invoke("rules:reload"),
  setSettings: (next) => ipcRenderer.invoke("settings:set", next),
  agentsStatus: () => ipcRenderer.invoke("agents:status"),
  setAgents: (on) => ipcRenderer.invoke("agents:set", on),
  agentsNewToken: () => ipcRenderer.invoke("agents:new-token"),
  shareTab: (id, on) => ipcRenderer.invoke("tab:agent-share", id, on),
  runAgent: (goal) => ipcRenderer.invoke("agent:run", goal),
  stopAgent: () => ipcRenderer.invoke("agent:stop"),
  searchStatus: () => ipcRenderer.invoke("search:status"),
  testSource: (id) => ipcRenderer.invoke("search:test", id),
  shot: (id) => ipcRenderer.invoke("library:shot", id),
  savePage: (id) => ipcRenderer.invoke("library:save", id),
  grabMedia: (id, url) => ipcRenderer.invoke("library:grab", id, url),
  libraryList: () => ipcRenderer.invoke("library:list"),
  removeLibraryItem: (id) => ipcRenderer.invoke("library:remove", id),
  openLibraryFolder: () => ipcRenderer.invoke("library:open-folder"),
  revealFile: (file) => ipcRenderer.invoke("library:reveal", file),
  toggleTabAudio: (id) => ipcRenderer.invoke("tab:audio", id),
  resetTabAudio: (id) => ipcRenderer.invoke("tab:audio-reset", id),
  setSoundAll: (on) => ipcRenderer.invoke("audio:all", on),
  moveTabs: (order) => ipcRenderer.invoke("tab:order", order),
  pip: (id) => ipcRenderer.invoke("tab:pip", id),
  openExternal: (url) => ipcRenderer.invoke("open-external", url),
  askPage: (id, question, history) => ipcRenderer.invoke("ai:ask", id, question, history),
  chatInfo: () => ipcRenderer.invoke("ai:chat-info"),
  bookmarkSearch: (q, limit) => ipcRenderer.invoke("bookmarks:search", q, limit),
  bookmarkHas: (url) => ipcRenderer.invoke("bookmarks:has", url),
  bookmarkToggle: (url, title) => ipcRenderer.invoke("bookmarks:toggle", url, title),
  bookmarkRemove: (url) => ipcRenderer.invoke("bookmarks:remove", url),
  onTabEvent: (fn) => {
    ipcRenderer.on("tab:event", (_e, payload) => fn(payload));
  },
  onCommand: (fn) => {
    ipcRenderer.on("ui:command", (_e, payload) => fn(payload));
  },
});
