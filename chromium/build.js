// Builds NODE for Chromium (engine test, B51 step 1) into chromium/dist:
//   node chromium/build.js
// Then load chromium/dist as an unpacked extension (chrome://extensions →
// Developer mode → Load unpacked) in Chromium, Brave, Edge or Chrome.
//
// The shared core/ modules are bundled with esbuild. The page scripts in
// core/page-scripts.js are code strings (the desktop app runs them with
// executeJavaScript); extensions cannot evaluate strings, so this build writes
// them into content.js as plain code.
const fs = require("fs");
const path = require("path");
const esbuild = require("esbuild");
const scripts = require("../core/page-scripts");
const pkg = require("../package.json");

const SRC = path.join(__dirname, "src");
const OUT = path.join(__dirname, "dist");
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, "fonts"), { recursive: true });

const manifest = {
  manifest_version: 3,
  name: "NODE",
  version: pkg.version,
  description: "NODE's research features for Chromium browsers: suggestions from the page you are reading, autoplay in up to 4 tabs, center on click, Talk.",
  icons: { 128: "icon.png" },
  action: { default_title: "NODE" },
  side_panel: { default_path: "sidepanel.html" },
  background: { service_worker: "background.js" },
  permissions: ["sidePanel", "tabs", "storage"],
  host_permissions: ["<all_urls>"],
  content_scripts: [{ matches: ["http://*/*", "https://*/*"], js: ["content.js"], run_at: "document_idle", all_frames: false }],
};
fs.writeFileSync(path.join(OUT, "manifest.json"), JSON.stringify(manifest, null, 2));

const content = `// Generated by chromium/build.js from core/page-scripts.js. Do not edit.
(() => {
  if (window.__nodeExt) return;
  window.__nodeExt = true;
  const extract = () => ${scripts.extractionScript()};
  const autoplay = () => ${scripts.autoplayScript("on")};
  const pauseForLimit = () => ${scripts.pauseForLimitScript()};
  const resume = () => ${scripts.resumeScript()};
  const anyPlaying = () => ${scripts.anyPlayingScript()};
  ${scripts.centerOnClickScript()};
  const send = (m) => chrome.runtime.sendMessage(m).catch(() => {});
  // Media in this tab started or stopped: tell the playback limit.
  document.addEventListener("play", () => send({ type: "media-playing" }), true);
  const stopped = () => setTimeout(() => { if (!anyPlaying()) send({ type: "media-stopped" }); }, 50);
  document.addEventListener("pause", stopped, true);
  document.addEventListener("ended", stopped, true);
  chrome.runtime.onMessage.addListener((msg, _sender, reply) => {
    if (msg.type === "extract") reply(extract());
    else if (msg.type === "pause-for-limit") reply(pauseForLimit());
    else if (msg.type === "resume") reply(resume());
    return false;
  });
  autoplay();
  window.addEventListener("load", autoplay);
  send({ type: "page-settled" });
})();
`;
fs.writeFileSync(path.join(OUT, "content.js"), content);

for (const entry of ["background.js", "sidepanel.js"]) {
  esbuild.buildSync({ entryPoints: [path.join(SRC, entry)], bundle: true, format: entry === "background.js" ? "esm" : "iife", platform: "browser", target: "chrome120", outfile: path.join(OUT, entry), logLevel: "warning" });
}
manifest.background.type = "module";
fs.writeFileSync(path.join(OUT, "manifest.json"), JSON.stringify(manifest, null, 2));

fs.copyFileSync(path.join(SRC, "sidepanel.html"), path.join(OUT, "sidepanel.html"));
fs.copyFileSync(path.join(SRC, "panel.css"), path.join(OUT, "panel.css"));
fs.copyFileSync(path.join(__dirname, "..", "renderer", "styles.css"), path.join(OUT, "styles.css"));
for (const f of fs.readdirSync(path.join(__dirname, "..", "renderer", "fonts"))) fs.copyFileSync(path.join(__dirname, "..", "renderer", "fonts", f), path.join(OUT, "fonts", f));
fs.copyFileSync(path.join(__dirname, "..", "build", "icon.png"), path.join(OUT, "icon.png"));
console.log("NODE for Chromium built in", path.relative(process.cwd(), OUT), "-", fs.readdirSync(OUT).join(", "));
