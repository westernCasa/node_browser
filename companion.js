// The Google window (B52): a separate Chromium-based browser window that NODE
// starts for Google account pages, because Google refuses sign-in inside apps
// built on Electron.
//
// How it works:
// - NODE finds a Chromium-based browser on the computer (Brave, Chromium, Edge,
//   Vivaldi, Chrome, in that order, or the path set in Settings) and starts it
//   with its own profile folder in NODE's data folder, so it is kept apart from
//   the person's normal browser and its sign-ins stay between NODE sessions.
// - The browser is started normally: no remote debugging port and no
//   automation switches. Google refuses sign-in in browsers under automation.
// - A small NODE extension is loaded into that window. It reports visited
//   pages to NODE (for history), applies center-on-click and autoplay, and
//   brings an already open page to the front instead of opening it twice. It
//   talks to NODE over a local HTTP server on 127.0.0.1 that only accepts
//   requests carrying a random token.
// - Some browsers (Google Chrome since version 137) refuse extensions loaded
//   this way. The window then still works for sign-in, in "basic mode".

const fs = require("fs");
const os = require("os");
const path = require("path");
const http = require("http");
const crypto = require("crypto");
const { spawn, execFileSync } = require("child_process");
const { centerOnClickScript, autoplayScript } = require("./core/page-scripts");

const EXT_VERSION = "1.0.0";

function candidates(platform = process.platform, env = process.env) {
  if (platform === "darwin") {
    const apps = [
      ["Brave", "Brave Browser.app/Contents/MacOS/Brave Browser"],
      ["Chromium", "Chromium.app/Contents/MacOS/Chromium"],
      ["Microsoft Edge", "Microsoft Edge.app/Contents/MacOS/Microsoft Edge"],
      ["Vivaldi", "Vivaldi.app/Contents/MacOS/Vivaldi"],
      ["Google Chrome", "Google Chrome.app/Contents/MacOS/Google Chrome"],
    ];
    const roots = ["/Applications", path.join(os.homedir(), "Applications")];
    return apps.flatMap(([name, rel]) => roots.map((r) => ({ name, path: path.join(r, rel) })));
  }
  if (platform === "win32") {
    const roots = [env.LOCALAPPDATA, env.PROGRAMFILES, env["PROGRAMFILES(X86)"]].filter(Boolean);
    const apps = [
      ["Brave", "BraveSoftware\\Brave-Browser\\Application\\brave.exe"],
      ["Chromium", "Chromium\\Application\\chrome.exe"],
      ["Microsoft Edge", "Microsoft\\Edge\\Application\\msedge.exe"],
      ["Vivaldi", "Vivaldi\\Application\\vivaldi.exe"],
      ["Google Chrome", "Google\\Chrome\\Application\\chrome.exe"],
    ];
    return apps.flatMap(([name, rel]) => roots.map((r) => ({ name, path: path.win32.join(r, rel) })));
  }
  const bins = [
    ["Brave", "brave-browser"],
    ["Brave", "brave"],
    ["Chromium", "chromium"],
    ["Chromium", "chromium-browser"],
    ["Microsoft Edge", "microsoft-edge"],
    ["Vivaldi", "vivaldi"],
    ["Google Chrome", "google-chrome"],
  ];
  const dirs = (env.PATH || "").split(":").filter(Boolean);
  return bins.flatMap(([name, bin]) => dirs.map((d) => ({ name, path: path.join(d, bin) })));
}

function nameFor(file) {
  const f = file.toLowerCase();
  if (f.includes("brave")) return "Brave";
  if (f.includes("edge")) return "Microsoft Edge";
  if (f.includes("vivaldi")) return "Vivaldi";
  if (f.includes("google chrome") || f.includes("google-chrome") || /google[\\/]chrome/.test(f)) return "Google Chrome";
  return "Chromium";
}

function findBrowser(override) {
  const isFile = (p) => {
    try {
      return fs.statSync(p).isFile();
    } catch (_) {
      return false;
    }
  };
  // Settings path, then NODE_GOOGLE_BROWSER (used by the tests), then the list.
  for (const p of [override, process.env.NODE_GOOGLE_BROWSER]) {
    if (p && isFile(p)) return { name: nameFor(p), path: p };
  }
  return candidates().find((c) => isFile(c.path)) || null;
}

// ---- The extension loaded into the Google window ----

function extensionFiles({ autoplay }) {
  const manifest = {
    manifest_version: 3,
    name: "NODE link",
    version: EXT_VERSION,
    description: "Connects this window to NODE: history, center on click, autoplay.",
    background: { service_worker: "background.js" },
    permissions: ["tabs"],
    host_permissions: ["http://127.0.0.1/*"],
    content_scripts: [{ matches: ["http://*/*", "https://*/*"], js: ["content.js"], run_at: "document_idle", all_frames: false }],
  };
  const background = `// Generated by NODE (companion.js). Rewritten each time NODE starts.
let cfg = null;
async function config() {
  if (!cfg) cfg = await (await fetch(chrome.runtime.getURL("config.json"), { cache: "no-store" })).json();
  return cfg;
}
async function post(route, body, retry = true) {
  try {
    const c = await config();
    const r = await fetch("http://127.0.0.1:" + c.port + route, {
      method: "POST",
      headers: { "content-type": "application/json", "x-node-token": c.token },
      body: JSON.stringify(body),
    });
    if (!r.ok) throw new Error(String(r.status));
  } catch (e) {
    // NODE may have restarted on another port: read the config again once.
    cfg = null;
    if (retry) return post(route, body, false);
  }
}
post("/ext/hello", { version: chrome.runtime.getManifest().version, agent: navigator.userAgent });

// NODE asks for a page through http://127.0.0.1:<port>/node/open?u=<address>.
// If that page is already open here, show it and drop the helper tab.
const OPEN = /^http:\\/\\/127\\.0\\.0\\.1:\\d+\\/node\\/open\\?/;
const handled = new Set();
const strip = (u) => String(u || "").split("#")[0].replace(/\\/$/, "");
async function maybeHelper(tabId, url) {
  if (!url || !OPEN.test(url) || handled.has(tabId)) return;
  handled.add(tabId);
  setTimeout(() => handled.delete(tabId), 10000);
  let target = "";
  try {
    target = new URL(url).searchParams.get("u") || "";
  } catch (_) {}
  if (!target) return;
  const all = await chrome.tabs.query({});
  const found = all.find((t) => t.id !== tabId && strip(t.url) === strip(target));
  if (!found) return; // NODE's server forwards the helper tab to the page.
  await chrome.tabs.update(found.id, { active: true });
  await chrome.windows.update(found.windowId, { focused: true });
  chrome.tabs.remove(tabId).catch(() => {});
}
chrome.tabs.onCreated.addListener((tab) => maybeHelper(tab.id, tab.pendingUrl || tab.url));
chrome.tabs.onUpdated.addListener((tabId, info, tab) => {
  if (info.url) maybeHelper(tabId, info.url);
  if (info.status === "complete" && /^https?:/.test(tab.url || "") && !OPEN.test(tab.url)) {
    post("/ext/visit", { url: tab.url, title: tab.title || "" });
  }
});
`;
  const content = `// Generated by NODE (companion.js) from core/page-scripts.js.
if (!window.__nodeLink) {
  window.__nodeLink = true;
  ${centerOnClickScript()};
  const autoplay = () => { ${autoplay === "off" ? "" : autoplayScript(autoplay === "muted" ? "muted" : "on")}; };
  autoplay();
  window.addEventListener("load", autoplay);
}
`;
  return { "manifest.json": JSON.stringify(manifest, null, 2), "background.js": background, "content.js": content };
}

// ---- Companion controller ----

function createCompanion({ userData, getSettings, getBounds, onVisit, onChange = () => {}, spawnFn = spawn }) {
  const root = path.join(userData, "google-window");
  const extDir = path.join(root, "extension");
  const profileDir = path.join(root, "profile");
  const stateFile = path.join(root, "state.json");
  let state = {};
  try {
    state = JSON.parse(fs.readFileSync(stateFile, "utf8"));
  } catch (_) {}
  if (!state.token) state.token = crypto.randomBytes(24).toString("hex");
  let server = null;
  let port = 0;
  let child = null;
  let linkSeen = 0; // last time the extension reached NODE
  let lastError = "";

  const saveState = () => {
    fs.mkdirSync(root, { recursive: true });
    fs.writeFileSync(stateFile, JSON.stringify({ token: state.token, port }, null, 2));
  };

  function tokenOk(req, url) {
    const t = req.headers["x-node-token"] || url.searchParams.get("t") || "";
    const a = Buffer.from(String(t));
    const b = Buffer.from(state.token);
    return a.length === b.length && crypto.timingSafeEqual(a, b);
  }

  function handle(req, res) {
    const url = new URL(req.url, "http://127.0.0.1");
    const send = (code, body = "", headers = {}) => {
      res.writeHead(code, { "content-type": "text/plain", ...headers });
      res.end(body);
    };
    if (!tokenOk(req, url)) return send(403, "forbidden");
    if (req.method === "GET" && url.pathname === "/node/open") {
      const target = url.searchParams.get("u") || "";
      if (!/^https?:\/\//i.test(target)) return send(400, "bad address");
      return send(302, "", { location: target, "cache-control": "no-store" });
    }
    if (req.method === "POST" && url.pathname.startsWith("/ext/")) {
      let body = "";
      req.on("data", (c) => {
        body += c;
        if (body.length > 64 * 1024) req.destroy();
      });
      req.on("end", () => {
        let msg = {};
        try {
          msg = JSON.parse(body || "{}");
        } catch (_) {}
        const first = !linkSeen;
        linkSeen = Date.now();
        if (url.pathname === "/ext/visit" && /^https?:\/\//.test(msg.url || "")) onVisit(String(msg.url), String(msg.title || ""));
        if (first) onChange(status());
        send(204);
      });
      return;
    }
    send(404, "not found");
  }

  function startServer() {
    if (server) return Promise.resolve(port);
    const listen = (p) =>
      new Promise((resolve, reject) => {
        const s = http.createServer(handle);
        s.once("error", reject);
        s.listen(p, "127.0.0.1", () => resolve(s));
      });
    // Reuse last session's port, so a Google window left open keeps working.
    return listen(state.port || 0)
      .catch(() => listen(0))
      .then((s) => {
        server = s;
        port = s.address().port;
        saveState();
        return port;
      });
  }

  function writeExtension() {
    fs.mkdirSync(extDir, { recursive: true });
    const files = extensionFiles({ autoplay: getSettings().autoplay });
    for (const [name, text] of Object.entries(files)) fs.writeFileSync(path.join(extDir, name), text);
    fs.writeFileSync(path.join(extDir, "config.json"), JSON.stringify({ port, token: state.token }));
  }

  function browser() {
    return findBrowser(getSettings().browser);
  }

  // Opens an address in the Google window, or shows it if already open there.
  // Returns false when no Chromium-based browser was found.
  async function open(target) {
    const b = browser();
    if (!b) {
      lastError = "No Chromium-based browser found";
      onChange(status());
      return false;
    }
    await startServer();
    writeExtension();
    fs.mkdirSync(profileDir, { recursive: true });
    const helper = `http://127.0.0.1:${port}/node/open?t=${state.token}&u=${encodeURIComponent(target)}`;
    const args = [
      `--user-data-dir=${profileDir}`,
      "--no-first-run",
      "--no-default-browser-check",
      `--load-extension=${extDir}`,
      // Chrome 137+ ignores --load-extension unless this feature is turned off
      // (and may ignore it entirely later). Other browsers ignore the switch.
      "--disable-features=DisableLoadExtensionCommandLineSwitch",
      "--autoplay-policy=no-user-gesture-required",
    ];
    const bounds = getBounds?.();
    if (bounds && !(child && child.exitCode === null)) {
      args.push(`--window-position=${Math.round(bounds.x)},${Math.round(bounds.y)}`, `--window-size=${Math.round(bounds.width)},${Math.round(bounds.height)}`);
    }
    // Tests add a debugging port here to look at the window's tabs. NODE
    // itself never does: Google refuses sign-in in browsers under automation.
    if (process.env.NODE_GOOGLE_EXTRA_ARGS) args.push(...process.env.NODE_GOOGLE_EXTRA_ARGS.split(" ").filter(Boolean));
    args.push(helper);
    try {
      // When the window is already running, the browser hands the address to
      // it and the new process exits at once.
      const p = spawnFn(b.path, args, { detached: true, stdio: "ignore" });
      p.on?.("error", (e) => {
        lastError = String(e.message || e);
        onChange(status());
      });
      p.unref?.();
      if (!(child && child.exitCode === null)) child = p;
      lastError = "";
      onChange(status());
      return true;
    } catch (e) {
      lastError = String(e.message || e);
      onChange(status());
      return false;
    }
  }

  function status() {
    const b = browser();
    return {
      browser: b ? b.name : "",
      path: b ? b.path : "",
      // "linked" once the NODE extension has reached NODE this session.
      link: linkSeen ? "linked" : child ? "waiting" : "not started",
      lastSeen: linkSeen,
      error: lastError,
    };
  }

  function stop() {
    try {
      server?.close();
    } catch (_) {}
    server = null;
  }

  return { open, status, stop, startServer, get port() { return port; }, get token() { return state.token; } };
}

module.exports = { createCompanion, findBrowser, candidates, extensionFiles, nameFor };
